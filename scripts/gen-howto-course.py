#!/usr/bin/env python3
"""Generate supabase/migrations/169_howto_video_course.sql from the how-to registry.

usage: python3 scripts/gen-howto-course.py
Idempotent SQL: upserts the 'how-to-videos' course (All staff) and one lesson per
registry entry (matched by video URL, so completions are never wiped). No
sequential unlock: the course page lists every lesson open.
"""
import pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = (ROOT / "src/lib/how-to/videos.ts").read_text()
OUT = ROOT / "supabase/migrations/169_howto_video_course.sql"

base = re.search(r'HOWTO_BUNNY_BASE\s*=\s*"([^"]+)"', SRC).group(1)
slug = re.search(r'HOW_TO_COURSE_SLUG\s*=\s*"([^"]+)"', SRC).group(1)
block = SRC[SRC.index("export const HOW_TO_VIDEOS"):]
block = block[: block.index("];")]
entries = []
for m in re.finditer(r"\{([^{}]*)\}", block):
    body = m.group(1)
    f = dict(re.findall(r'(\w+):\s*"([^"]*)"', body))
    if {"slug", "route", "title", "file"} <= f.keys():
        entries.append(f)


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


lines = [
    "-- How-to videos course (generated by scripts/gen-howto-course.py - safe to re-run).",
    "insert into public.training_courses (slug, title, blurb, audience, status, sort_order)",
    f"values ({q(slug)}, 'How-to videos',",
    "  'Short videos showing how to use each Hub module. Watch at least 90% of a video to complete it: 5 points per video and a 100-point bonus when you finish them all.',",
    "  'All staff', 'published', 1000)",
    "on conflict (slug) do update set",
    "  title = excluded.title, blurb = excluded.blurb, audience = excluded.audience,",
    "  status = 'published', updated_at = now();",
    "",
]
for i, e in enumerate(entries, 1):
    url = f"{base}/{e['file']}"
    title = f"{e['title']} how-to"
    body = (
        f"A short how-to for {e['title']}. You can also open it any time from the "
        f"Watch how-to video link at the top of the page ({e['route']})."
    )
    lines += [
        f"-- {i}. {e['title']}",
        "update public.training_lessons l set",
        f"  title = {q(title)}, body = {q(body)}, sort_order = {i * 10}, updated_at = now()",
        "from public.training_courses c",
        f"where c.slug = {q(slug)} and l.course_id = c.id and l.resource_href = {q(url)};",
        "insert into public.training_lessons (course_id, sort_order, title, body, resource_href, resource_label)",
        f"select c.id, {i * 10}, {q(title)}, {q(body)}, {q(url)}, ''",
        f"from public.training_courses c where c.slug = {q(slug)}",
        "  and not exists (select 1 from public.training_lessons l",
        f"    where l.course_id = c.id and l.resource_href = {q(url)});",
        "",
    ]
OUT.write_text("\n".join(lines))
print(f"wrote {OUT.relative_to(ROOT)} with {len(entries)} lesson(s)")
